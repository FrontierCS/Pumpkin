//! `pumpkin-frontier-cs`, the FrontierCS factory's command line. [`flags`] holds its grammar
//! and describes each command, as `pumpkin-frontier-cs --help` prints it.

use std::fmt;
use std::io::{self, Write as _};
use std::path::Path;
use std::process::ExitCode;

use pumpkin_docker::{ContextName, Engine};
use pumpkin_frontier_cs::Task;
use stdx::Context;

/// The grammar of `pumpkin-frontier-cs`'s command line, from which xflags generates its parser,
/// the types below and `--help`.
mod flags {
    #![expect(
        unreachable_pub,
        reason = "xflags declares the types it generates `pub`"
    )]
    #![expect(
        clippy::allow_attributes,
        clippy::allow_attributes_without_reason,
        reason = "xflags generates `#[allow(dead_code)]`, without a reason, on its parsers"
    )]

    use std::path::PathBuf;

    xflags::xflags! {
        src "./src/main.rs"

        /// The FrontierCS factory, for tasks ported from FrontierCS to Pumpkin.
        cmd pumpkin-frontier-cs {
            /// Builds the task's images, unless the engine has them built from the same
            /// inputs: the agent's base from `agent-base/Dockerfile`, and the verifier's from
            /// `verifier/Dockerfile`, with the task's directory as their context, each tagged
            /// `pumpkin-frontier-cs/<problem id>/<agent-base or verifier>:<digest>` by the digest
            /// of the build's options, its recipe and its context's files; then the agent's,
            /// `pumpkin-frontier-cs/<problem id>/agent:<digest>`, its base with Codex added,
            /// which the engine fetches and checks by its digest. Refuses first a task's recipe
            /// that may have Docker fetch an image not pinned by digest, a frontend or a URL. A
            /// build's progress goes to standard error. Prints the IDs of the agent's and the
            /// verifier's images as JSON, and exits with 0, 2 on a usage error, and 1 on any
            /// other error.
            cmd build {
                /// The task's directory, `tasks/frontier-cs/<problem id>`.
                required task: PathBuf
                /// The Docker context that reaches the engine to build on, as `docker context
                /// ls` lists it.
                required --docker-context name: String
            }
        }
    }
    // generated start
    // The following code is generated by `xflags` macro.
    // Run `env UPDATE_XFLAGS=1 cargo build` to regenerate.
    #[derive(Debug)]
    pub struct PumpkinFrontierCs {
        pub subcommand: PumpkinFrontierCsCmd,
    }

    #[derive(Debug)]
    pub enum PumpkinFrontierCsCmd {
        Build(Build),
    }

    #[derive(Debug)]
    pub struct Build {
        pub task: PathBuf,

        pub docker_context: String,
    }

    impl PumpkinFrontierCs {
        #[allow(dead_code)]
        pub fn from_env_or_exit() -> Self {
            Self::from_env_or_exit_()
        }

        #[allow(dead_code)]
        pub fn from_env() -> xflags::Result<Self> {
            Self::from_env_()
        }

        #[allow(dead_code)]
        pub fn from_vec(args: Vec<std::ffi::OsString>) -> xflags::Result<Self> {
            Self::from_vec_(args)
        }
    }
    // generated end
}

fn main() -> ExitCode {
    let done = match flags::PumpkinFrontierCs::from_env().map(|flags| flags.subcommand) {
        Ok(flags::PumpkinFrontierCsCmd::Build(flags::Build {
            task,
            docker_context,
        })) => build(&task, docker_context),
        Err(error) if error.is_help() => error.exit(),
        // A usage error exits with 2, as xflags exits, apart from the command's errors.
        Err(error) => {
            say(format_args!("{error}: see `pumpkin-frontier-cs --help`"));
            return ExitCode::from(2);
        }
    };
    match done {
        Ok(()) => ExitCode::SUCCESS,
        Err(message) => {
            say(message);
            ExitCode::FAILURE
        }
    }
}

/// Builds the images of the task in `dir` on the engine that the context named `context`
/// reaches, and prints their IDs. The task is read first, so a task it refuses needs no engine.
fn build(dir: &Path, context: String) -> Result<(), String> {
    let task = Task::load(dir)?;
    let engine = Engine::connect(ContextName::try_from(context)?)?;
    let images = task.build(&engine)?;
    let mut stdout = io::stdout().lock();
    (serde_json::to_writer_pretty(&mut stdout, &images).map_err(io::Error::from))
        .and_then(|()| writeln!(stdout))
        .context("printing the images' IDs failed")
}

/// Writes `message` to standard error, as `pumpkin-frontier-cs: <message>`.
fn say(message: impl fmt::Display) {
    // Writing to a terminal that has hung up fails, and `eprintln!` would panic; the exit
    // status still says how the command ended.
    let _ = writeln!(io::stderr(), "pumpkin-frontier-cs: {message}");
}
