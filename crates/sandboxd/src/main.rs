//! `sandboxd`, the supervisor that runs in every sandbox, and, run under the file name
//! `sandboxctl`, the shim through which callers in the sandbox make ops ([`ctl`]). [`flags`]
//! holds `sandboxd`'s grammar, as `sandboxd --help` prints it.
//!
//! It meets the gateway, at a Unix socket of the sandbox's own, opens the session
//! ([`schema::sandbox`]) with its hello, and serves it until the gateway closes it:
//! it puts and collects trees, starts commands and reports their exits, and freezes the sandbox.
//! When the session ends it kills its commands and exits, which stops a sandbox it is first in.
//!
//! With `--ops`, it also serves [ops], which it carries to the session's owner; without it,
//! nothing in its sandbox can make one. With `--model`, it also serves the [model] endpoint, whose
//! requests it carries to the session's owner likewise.
//!
//! As a sandbox's first process (PID 1) it reaps the orphans the kernel hands it, and freezing
//! kills every other process in the sandbox. Run as any other process, as in tests, it kills
//! only the process groups of the commands still running.
//!
//! It runs as the role's user from the start and needs no privileges: everything it does, the
//! role's own code could do too, so it is no boundary within its sandbox. It does make itself
//! non-dumpable first, so that the role's code can't reach it through `/proc`
//! ([`sys::make_non_dumpable`] says why).

use std::ffi::OsString;
use std::fmt::Display;
use std::io::{self, Write};
use std::path::Path;
use std::process::ExitCode;

use crate::session::Gateway;

mod commands;
mod ctl;
mod files;
mod model;
mod ops;
mod session;
mod sys;

/// The grammar of `sandboxd`'s command line, from which xflags generates its parser, the types
/// below and `--help`.
mod flags {
    #![expect(
        unreachable_pub,
        reason = "xflags declares the types it generates `pub`"
    )]
    #![expect(
        clippy::allow_attributes,
        clippy::allow_attributes_without_reason,
        reason = "xflags generates `#[allow(dead_code)]`, without a reason, on its parsers"
    )]

    use std::path::PathBuf;

    xflags::xflags! {
        src "./src/main.rs"

        /// Serves a sandbox's session as its supervisor, until the gateway ends it. Exits with
        /// 0 then, and with 1 on any error, bad arguments included.
        cmd sandboxd {
            /// The gateway's Unix socket, over which the session runs.
            required gateway: PathBuf
            /// Serves ops, which callers in the sandbox make through `sandboxctl`, at
            /// /pumpkin/sandboxctl/socket. sandboxd makes its directory, which must not exist
            /// yet, closed to all but its own user. Without it, nothing in the sandbox can make
            /// an op.
            optional --ops
            /// Serves the model endpoint, through which a harness in the sandbox makes model
            /// requests, at http://127.0.0.1:11235. The gateway must accept the session to take
            /// them, or the first ends it. Without it, nothing in the sandbox can make one.
            optional --model
        }
    }
    // generated start
    // The following code is generated by `xflags` macro.
    // Run `env UPDATE_XFLAGS=1 cargo build` to regenerate.
    #[derive(Debug)]
    pub struct Sandboxd {
        pub gateway: PathBuf,

        pub ops: bool,
        pub model: bool,
    }

    impl Sandboxd {
        #[allow(dead_code)]
        pub fn from_env_or_exit() -> Self {
            Self::from_env_or_exit_()
        }

        #[allow(dead_code)]
        pub fn from_env() -> xflags::Result<Self> {
            Self::from_env_()
        }

        #[allow(dead_code)]
        pub fn from_vec(args: Vec<std::ffi::OsString>) -> xflags::Result<Self> {
            Self::from_vec_(args)
        }
    }
    // generated end
}

#[expect(
    clippy::print_stderr,
    reason = "sandboxd reports why it stopped on its standard error, which the provider keeps"
)]
fn main() -> ExitCode {
    stdx::abort_on_panic();
    let mut args = std::env::args_os();
    let name = args.next().unwrap_or_default();
    let args: Vec<OsString> = args.collect();
    if Path::new(&name).file_name() == Some("sandboxctl".as_ref()) {
        return ctl::main(args);
    }
    let flags::Sandboxd {
        gateway,
        ops,
        model,
    } = match flags::Sandboxd::from_vec(args) {
        Ok(flags) => flags,
        Err(error) if error.is_help() => {
            print_line(io::stdout(), error);
            return ExitCode::SUCCESS;
        }
        // Bad arguments exit with 1, as sandboxd's other errors do, and not with the 2 that
        // xflags exits with, which `--help` doesn't list.
        Err(error) => {
            eprintln!("sandboxd: {error}: see `sandboxd --help`");
            return ExitCode::FAILURE;
        }
    };
    if let Err(error) = sys::make_non_dumpable() {
        eprintln!("sandboxd: making the process non-dumpable failed: {error}");
        return ExitCode::FAILURE;
    }
    match session::serve(&Gateway::Socket(gateway), ops, model) {
        Ok(()) => ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("sandboxd: {error}");
            ExitCode::FAILURE
        }
    }
}

/// Writes `line` to `stream`, standard output or standard error, and ignores a failed write:
/// what `sandboxd` and `sandboxctl` print never changes their outcome, which their exit code
/// reports even when nobody reads their output.
fn print_line(mut stream: impl Write, line: impl Display) {
    let _ = writeln!(stream, "{line}");
}
