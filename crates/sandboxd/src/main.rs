//! `sandboxd`, the supervisor that runs in every sandbox. [`flags`] holds its grammar, as
//! `sandboxd --help` prints it.
//!
//! It connects to the gateway at the Unix socket named by its one argument and serves the
//! session ([`pumpkin_schema::sandbox`]) until the gateway closes it: it writes the trees it is
//! put, starts commands and reports their exits, freezes the sandbox, and sends
//! the trees it is asked to collect. When the session ends it kills its commands and exits,
//! which stops a sandbox whose first process it is.
//!
//! As a sandbox's first process (PID 1) it reaps the orphans the kernel hands it, and freezing
//! kills every other process in the sandbox. Run as any other process, as in tests, it kills
//! only the process groups of the commands still running.
//!
//! It runs as the role's user from the start and needs no privileges: everything it does,
//! the role's own code could do too. That is why its reports are untrusted wherever the role
//! runs untrusted code. It does make itself non-dumpable first, so that the role's code can't
//! reach it through `/proc` ([`sys::make_non_dumpable`] says why).

use std::io::{self, Write};
use std::process::ExitCode;

mod collect;
mod commands;
mod session;
mod sys;

/// The grammar of `sandboxd`'s command line, from which xflags generates its parser, the types
/// below and `--help`.
mod flags {
    #![expect(
        unreachable_pub,
        reason = "xflags declares the types it generates `pub`"
    )]

    use std::path::PathBuf;

    xflags::xflags! {
        src "./src/main.rs"

        /// Serves a sandbox's session as its supervisor, until the gateway ends it. Exits with
        /// 0 then, and with 1 on any error, bad arguments included.
        cmd sandboxd {
            /// The gateway's Unix socket, over which the session runs.
            required gateway: PathBuf
        }
    }
    // generated start
    // The following code is generated by `xflags` macro.
    // Run `env UPDATE_XFLAGS=1 cargo build` to regenerate.
    #[derive(Debug)]
    pub struct Sandboxd {
        pub gateway: PathBuf,
    }

    impl Sandboxd {
        #[allow(dead_code)]
        pub fn from_env_or_exit() -> Self {
            Self::from_env_or_exit_()
        }

        #[allow(dead_code)]
        pub fn from_env() -> xflags::Result<Self> {
            Self::from_env_()
        }

        #[allow(dead_code)]
        pub fn from_vec(args: Vec<std::ffi::OsString>) -> xflags::Result<Self> {
            Self::from_vec_(args)
        }
    }
    // generated end
}

#[expect(
    clippy::print_stderr,
    reason = "sandboxd reports why it stopped on its standard error, which the provider keeps"
)]
fn main() -> ExitCode {
    sys::make_non_dumpable();
    let flags::Sandboxd { gateway } = match flags::Sandboxd::from_env() {
        Ok(flags) => flags,
        Err(error) if error.is_help() => {
            // Help that can't be written changes nothing.
            let _ = writeln!(io::stdout(), "{error}");
            return ExitCode::SUCCESS;
        }
        // Bad arguments exit with 1, as sandboxd's other errors do, and not with the 2 that
        // xflags exits with, which `--help` doesn't list.
        Err(error) => {
            eprintln!("sandboxd: {error}: see `sandboxd --help`");
            return ExitCode::FAILURE;
        }
    };
    match session::serve(&gateway) {
        Ok(()) => ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("sandboxd: {error}");
            ExitCode::FAILURE
        }
    }
}
