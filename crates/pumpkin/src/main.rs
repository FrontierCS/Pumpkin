//! `pumpkin`, the operator's command line. [`flags`] holds its grammar and describes each
//! command, as `pumpkin --help` prints it. `run` runs a workflow with
//! [`runtime`], on the Docker provider, and [`config`] reads the deployment's
//! configuration.

use std::io::{self, Write as _};
use std::path::{Path, PathBuf};
use std::process::ExitCode;
use std::time::SystemTime;
use std::{env, fmt, fs};

use docker::{ContextName, Engine};
use runtime::{Ending, Record, Run};
use schema::ir;
use schema::workflow::Workflow;
use stdx::Context;

mod config;

/// The grammar of `pumpkin`'s command line, from which xflags generates its parser, the types
/// below and `--help`.
mod flags {
    #![expect(
        unreachable_pub,
        reason = "xflags declares the types it generates `pub`"
    )]
    #![expect(
        clippy::allow_attributes,
        clippy::allow_attributes_without_reason,
        reason = "xflags generates `#[allow(dead_code)]`, without a reason, on its parsers"
    )]

    use std::path::PathBuf;

    xflags::xflags! {
        src "./src/main.rs"

        /// The operator's command line, which runs workflows.
        cmd pumpkin {
            /// Runs a workflow on the Docker engine that a context reaches, with its record in
            /// `<runs>/<id>/`, and prints the record's `outcome.json`, a failed run's too. Says so
            /// first if the engine runs as root. Exits with 0 if the run finished with a score, 3 if it
            /// finished without one, 2 on a usage error, and 1 on any other error, a workflow
            /// it refuses and a run that failed included; every non-zero exit ends with a
            /// `pumpkin:` line on the standard error that says why. A signal that ends it may leave the
            /// run's containers stopped but not removed (the engine lists them by the label
            /// `pumpkin.run=<id>`), its socket directory in the temporary directory, and its
            /// record without an `outcome.json`. To outlive a logout, run it under `tmux` or
            /// `nohup`. Its record is locked while it runs, so `pumpkin wait` follows it from
            /// another shell.
            cmd run {
                /// The workflow's IR, as JSON.
                required ir: PathBuf
                /// The Docker context that reaches the engine to run on, as `docker context ls`
                /// lists it.
                required --docker-context name: String
                /// The static `sandboxd` binary for every sandbox, which `cargo xtask sandboxd`
                /// builds.
                required --sandboxd path: PathBuf
                /// The directory runs are recorded in: `$HOME/.local/share/pumpkin/runs` by
                /// default.
                optional --runs dir: PathBuf
                /// The deployment's configuration, read only for a workflow with a model
                /// route: a TOML file whose `[upstreams.<name>]` tables each give an upstream
                /// the route may reach, with the base `url` of its API, the `key_file` that
                /// holds its key, below the configuration's directory unless absolute, and the
                /// `models` it serves, each with the `name` a route allows and the
                /// `upstream_name` the upstream takes for it. No model is listed twice. The
                /// route reaches `/responses` below the upstream that serves every model it
                /// allows. `$HOME/.config/pumpkin/pumpkin.toml` by default.
                optional --config file: PathBuf
            }

            /// Waits until a run has ended, then prints its `outcome.json`, and exits as `run`
            /// does: with 0 if the run finished with a score, 3 if it finished without one, 2 on
            /// a usage error, and 1 on any other error, a run that failed or was lost, because its driver ended without an `outcome.json`, included. Says why on
            /// the standard error when the exit is not 0. It follows a run that `pumpkin run`
            /// is still driving, and ending it does not stop the run. A record made before
            /// records were locked has no `driver.pid`, and is refused.
            cmd wait {
                /// The run: its id, a prefix of its id or of the 8 random digits that end it,
                /// that no other run in `--runs` shares, or the path of its record, which has a
                /// `/`.
                required run: String
                /// The directory runs are recorded in: `$HOME/.local/share/pumpkin/runs` by
                /// default.
                optional --runs dir: PathBuf
            }
        }
    }
    // generated start
    // The following code is generated by `xflags` macro.
    // Run `env UPDATE_XFLAGS=1 cargo build` to regenerate.
    #[derive(Debug)]
    pub struct Pumpkin {
        pub subcommand: PumpkinCmd,
    }

    #[derive(Debug)]
    pub enum PumpkinCmd {
        Run(Run),
        Wait(Wait),
    }

    #[derive(Debug)]
    pub struct Run {
        pub ir: PathBuf,

        pub docker_context: String,
        pub sandboxd: PathBuf,
        pub runs: Option<PathBuf>,
        pub config: Option<PathBuf>,
    }

    #[derive(Debug)]
    pub struct Wait {
        pub run: String,

        pub runs: Option<PathBuf>,
    }

    impl Pumpkin {
        #[allow(dead_code)]
        pub fn from_env_or_exit() -> Self {
            Self::from_env_or_exit_()
        }

        #[allow(dead_code)]
        pub fn from_env() -> xflags::Result<Self> {
            Self::from_env_()
        }

        #[allow(dead_code)]
        pub fn from_vec(args: Vec<std::ffi::OsString>) -> xflags::Result<Self> {
            Self::from_vec_(args)
        }
    }
    // generated end
}

fn main() -> ExitCode {
    // A run's judge calls, and each session's reader, run on threads of their own.
    stdx::abort_on_panic();
    let done = match flags::Pumpkin::from_env().map(|flags| flags.subcommand) {
        Ok(flags::PumpkinCmd::Run(flags::Run {
            ir,
            docker_context,
            sandboxd,
            runs,
            config,
        })) => run(&ir, docker_context, &sandboxd, runs, config),
        Ok(flags::PumpkinCmd::Wait(flags::Wait { run, runs })) => wait(&run, runs),
        Err(error) if error.is_help() => error.exit(),
        // A usage error exits with 2, as xflags exits, apart from the command's errors.
        Err(error) => {
            say(format_args!("{error}: see `pumpkin --help`"));
            return ExitCode::from(2);
        }
    };
    match done {
        Ok(exit) => exit,
        Err(message) => {
            say(message);
            ExitCode::FAILURE
        }
    }
}

/// Runs the workflow whose IR is at `path` on the engine that the context named `context`
/// reaches, with `sandboxd` in every sandbox, records it in `runs`, or [`default_runs`], and
/// prints its outcome; returns the exit status that `run`'s help gives. A workflow with a model
/// route has its deployment's configuration read from `config`, or [`default_config`].
fn run(
    path: &Path,
    context: String,
    sandboxd: &Path,
    runs: Option<PathBuf>,
    config: Option<PathBuf>,
) -> Result<ExitCode, String> {
    // The IR, the context's name, the runs directory, the configuration and its upstream's key
    // are checked before the engine is reached, so a mistake in them needs no engine. A wrong
    // `sandboxd` is not: it is first used when the run publishes it, which is after the engine
    // is reached and the record is begun.
    let context = ContextName::try_from(context)?;
    let runs = match runs {
        Some(runs) => runs,
        None => default_runs()?,
    };
    let workflow = read_workflow(path)?;
    let serving = match &workflow.agent().sandbox.model_route {
        Some(route) => {
            let config = match config {
                Some(config) => config,
                None => default_config()?,
            };
            let serving = config::read(&config)?.serving(&route.models);
            Some(serving.context(config.display())?)
        }
        None => None,
    };
    let engine = engine(context)?;
    let run = Run::prepare(workflow, &runs, SystemTime::now(), serving)?;
    let dir = run.dir().to_owned();
    say(format_args!(
        "run {} records into {}",
        run.id(),
        dir.display()
    ));
    match run.execute(&engine, sandboxd) {
        // The run's lock is released, so its record says how it ended at once.
        Ok(_) => {
            let record = Record::open(&dir)?;
            let ending = record.wait(|| {})?;
            end(&record, &ending)
        }
        // `execute` wrote the failed run's `outcome.json` before it returned.
        Err(reason) => match print_outcome(&dir) {
            Ok(()) => Err(reason),
            Err(printing) => Err(format!("{reason}; {printing}")),
        },
    }
}

/// Waits until the run that `run` names in `runs`, or [`default_runs`], has ended, and prints its
/// outcome; returns the exit status that `wait`'s help gives.
fn wait(run: &str, runs: Option<PathBuf>) -> Result<ExitCode, String> {
    // A path needs no runs directory, and so no `HOME`.
    let record = if run.contains('/') {
        Record::open(Path::new(run))?
    } else {
        let runs = match runs {
            Some(runs) => runs,
            None => default_runs()?,
        };
        Record::find(&runs, run)?
    };
    let ending = record.wait(|| {
        say(format_args!(
            "following run {}: ending `pumpkin wait` does not stop it",
            record.id()
        ));
    })?;
    end(&record, &ending)
}

/// Prints the outcome of `record`, a run that has `ended`, and returns the exit status that
/// `run`'s and `wait`'s help give; a run without a score says why on the standard error.
fn end(record: &Record, ending: &Ending) -> Result<ExitCode, String> {
    print_outcome(record.dir())?;
    let id = record.id();
    Ok(match ending {
        Ending::Scored => ExitCode::SUCCESS,
        Ending::Unscored(why) => {
            say(format_args!("run {id} {why}"));
            ExitCode::from(3)
        }
        Ending::Failed(why) => {
            say(format_args!("run {id} {why}"));
            ExitCode::FAILURE
        }
    })
}

/// `$HOME/.local/share/pumpkin/runs`.
fn default_runs() -> Result<PathBuf, String> {
    Ok(home("name a directory with `--runs`")?.join(".local/share/pumpkin/runs"))
}

/// `$HOME/.config/pumpkin/pumpkin.toml`.
fn default_config() -> Result<PathBuf, String> {
    Ok(home("name the configuration with `--config`")?.join(".config/pumpkin/pumpkin.toml"))
}

/// The home directory, `HOME`; failing without one, the error says what the operator can do
/// `instead`.
fn home(instead: &str) -> Result<PathBuf, String> {
    // From `HOME` alone, not `XDG_DATA_HOME` or `XDG_CONFIG_HOME`: a run already reads `HOME`,
    // for `docker`, so where its files are takes no variable of its own.
    let home = env::var_os("HOME").filter(|home| !home.is_empty());
    home.map(PathBuf::from)
        .ok_or_else(|| format!("HOME is unset or empty: set it, or {instead}"))
}

/// The workflow whose IR is in the file at `path`.
fn read_workflow(path: &Path) -> Result<Workflow, String> {
    let json = fs::read(path).context(path.display())?;
    let ir: ir::Workflow = serde_json::from_slice(&json).context(path.display())?;
    Workflow::parse(&ir).map_err(|errors| {
        // Each problem is said on a line of its own, as cargo does, so that the error the
        // caller says last is still one line.
        let problems = errors.as_slice();
        for problem in problems {
            say(format_args!("{}: {problem}", path.display()));
        }
        let (count, s) = (problems.len(), if problems.len() == 1 { "" } else { "s" });
        format!(
            "{}: the workflow has {count} problem{s}: fix {} and run again",
            path.display(),
            if count == 1 { "it" } else { "them" }
        )
    })
}

/// The Docker engine that `context` reaches, reported. A rootful engine is announced, since its
/// `docker` group is root-equivalent.
fn engine(context: ContextName) -> Result<Engine, String> {
    let engine = Engine::connect(context)?;
    let report = engine.report();
    if !report.security.rootless {
        say(format_args!(
            "the Docker engine that context `{}` reaches runs as root, so its `docker` group is \
             root-equivalent: rootless Docker is recommended",
            report.context.as_str()
        ));
    }
    Ok(engine)
}

/// Prints the run's `outcome.json`, from its record in `dir`, on the standard output.
fn print_outcome(dir: &Path) -> Result<(), String> {
    let recorded = dir.join("outcome.json");
    let printed = fs::read(&recorded).context(recorded.display())?;
    let mut stdout = io::stdout().lock();
    (stdout.write_all(&printed))
        .and_then(|()| stdout.flush())
        .context("printing the outcome failed")
}

/// Writes `message` to standard error, as `pumpkin: <message>`.
fn say(message: impl fmt::Display) {
    // Writing to a terminal that has hung up fails, and `eprintln!` would panic; the exit
    // status and the run's record still say how it ended.
    let _ = writeln!(io::stderr(), "pumpkin: {message}");
}
