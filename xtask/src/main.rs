//! See <https://github.com/matklad/cargo-xtask/>.
//!
//! This is integrated as a `cargo` subcommand by using an alias in `.cargo/config.toml`.

#![expect(
    clippy::print_stderr,
    reason = "a command line reports on its standard error"
)]

use std::error::Error;
use std::path::Path;
use std::process::ExitCode;

use xshell::{Shell, cmd};

/// A task's result. `main` prints a failure, such as a command's, once, as `xtask: <error>`.
type Result<T> = std::result::Result<T, Box<dyn Error>>;

mod flags {
    #![expect(
        unreachable_pub,
        reason = "xflags declares the types it generates `pub`"
    )]

    xflags::xflags! {
        src "./src/main.rs"

        /// Contributor tasks.
        cmd xtask {
            /// Runs the checks every change must pass, in order, and stops at the first that
            /// fails.
            cmd ci {}
        }
    }
    // generated start
    // The following code is generated by `xflags` macro.
    // Run `env UPDATE_XFLAGS=1 cargo build` to regenerate.
    #[derive(Debug)]
    pub struct Xtask {
        pub subcommand: XtaskCmd,
    }

    #[derive(Debug)]
    pub enum XtaskCmd {
        Ci(Ci),
    }

    #[derive(Debug)]
    pub struct Ci;

    impl Xtask {
        #[allow(dead_code)]
        pub fn from_env_or_exit() -> Self {
            Self::from_env_or_exit_()
        }

        #[allow(dead_code)]
        pub fn from_env() -> xflags::Result<Self> {
            Self::from_env_()
        }

        #[allow(dead_code)]
        pub fn from_vec(args: Vec<std::ffi::OsString>) -> xflags::Result<Self> {
            Self::from_vec_(args)
        }
    }
    // generated end
}

fn main() -> ExitCode {
    match try_main() {
        Ok(()) => ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("xtask: {error}");
            ExitCode::FAILURE
        }
    }
}

/// Runs the task the command line names. xflags exits by itself on `--help`, with 0, and on a
/// command line it can't parse, with 2.
fn try_main() -> Result<()> {
    let flags = flags::Xtask::from_env_or_exit();
    let sh = Shell::new()?;
    sh.change_dir(root());
    match flags.subcommand {
        flags::XtaskCmd::Ci(flags::Ci) => ci(&sh),
    }
}

/// The workspace's root, which holds `xtask/`.
fn root() -> &'static Path {
    #[expect(clippy::expect_used, reason = "the workspace's root holds xtask/")]
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("xtask/ has a parent directory")
}

/// Runs the checks every change must pass, in order, and stops at the first that fails.
fn ci(sh: &Shell) -> Result<()> {
    cmd!(sh, "cargo fmt --check").run()?;
    let clippy = cmd!(
        sh,
        "cargo clippy --workspace --all-targets --locked -- --deny warnings"
    );
    clippy.run()?;
    let doc = cmd!(sh, "cargo doc --no-deps --workspace --locked");
    doc.env("RUSTDOCFLAGS", "--deny warnings").run()?;
    cmd!(sh, "cargo test --workspace --locked").run()?;
    Ok(())
}
