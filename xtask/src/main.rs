//! See <https://github.com/matklad/cargo-xtask/>.
//!
//! This is integrated as a `cargo` subcommand by using an alias in `.cargo/config.toml`.

#![expect(
    clippy::print_stdout,
    clippy::print_stderr,
    reason = "a command line reports on its standard output and error"
)]

use std::error::Error;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use xshell::{Shell, cmd};

/// A task's result. `main` prints a failure, such as a command's, once, as `xtask: <error>`.
type Result<T> = std::result::Result<T, Box<dyn Error>>;

/// The target the static `sandboxd` is built for.
const MUSL: &str = "x86_64-unknown-linux-musl";

mod flags {
    #![expect(
        unreachable_pub,
        reason = "xflags declares the types it generates `pub`"
    )]

    xflags::xflags! {
        src "./src/main.rs"

        /// Contributor tasks.
        cmd xtask {
            /// Runs the checks every change must pass, in order, and stops at the first that
            /// fails.
            cmd ci {
                /// Runs the Docker tests too, which are ignored otherwise, against the static
                /// sandboxd that `sandboxd` builds, through the Docker context
                /// `PUMPKIN_DOCKER_CONTEXT` names, or `default`.
                optional --docker
            }

            /// Builds the static sandboxd that every sandbox runs, and prints its path.
            cmd sandboxd {}
        }
    }
    // generated start
    // The following code is generated by `xflags` macro.
    // Run `env UPDATE_XFLAGS=1 cargo build` to regenerate.
    #[derive(Debug)]
    pub struct Xtask {
        pub subcommand: XtaskCmd,
    }

    #[derive(Debug)]
    pub enum XtaskCmd {
        Ci(Ci),
        Sandboxd(Sandboxd),
    }

    #[derive(Debug)]
    pub struct Ci {
        pub docker: bool,
    }

    #[derive(Debug)]
    pub struct Sandboxd;

    impl Xtask {
        #[allow(dead_code)]
        pub fn from_env_or_exit() -> Self {
            Self::from_env_or_exit_()
        }

        #[allow(dead_code)]
        pub fn from_env() -> xflags::Result<Self> {
            Self::from_env_()
        }

        #[allow(dead_code)]
        pub fn from_vec(args: Vec<std::ffi::OsString>) -> xflags::Result<Self> {
            Self::from_vec_(args)
        }
    }
    // generated end
}

fn main() -> ExitCode {
    match try_main() {
        Ok(()) => ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("xtask: {error}");
            ExitCode::FAILURE
        }
    }
}

/// Runs the task the command line names. xflags exits by itself on `--help`, with 0, and on a
/// command line it can't parse, with 2.
fn try_main() -> Result<()> {
    let flags = flags::Xtask::from_env_or_exit();
    let sh = Shell::new()?;
    sh.change_dir(root());
    match flags.subcommand {
        flags::XtaskCmd::Ci(flags::Ci { docker }) => ci(&sh, docker),
        flags::XtaskCmd::Sandboxd(flags::Sandboxd) => {
            println!("{}", sandboxd(&sh)?.display());
            Ok(())
        }
    }
}

/// The workspace's root, which holds `xtask/`.
fn root() -> &'static Path {
    #[expect(clippy::expect_used, reason = "the workspace's root holds xtask/")]
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("xtask/ has a parent directory")
}

/// Runs the checks every change must pass, in order, and stops at the first that fails. With
/// `docker`, it builds the static `sandboxd` before the tests, names it in `PUMPKIN_SANDBOXD`
/// and runs the ignored tests too, which are the tests that need Docker; they inherit
/// `PUMPKIN_DOCKER_CONTEXT`, which names the context they reach Docker through, and get
/// Docker's own variables set to reach no engine.
fn ci(sh: &Shell, docker: bool) -> Result<()> {
    cmd!(sh, "cargo fmt --check").run()?;
    let clippy = cmd!(
        sh,
        "cargo clippy --workspace --all-targets --locked -- --deny warnings"
    );
    clippy.run()?;
    let doc = cmd!(sh, "cargo doc --no-deps --workspace --locked");
    doc.env("RUSTDOCFLAGS", "--deny warnings").run()?;
    let test = cmd!(sh, "cargo test --workspace --locked");
    if docker {
        let sandboxd = sandboxd(sh)?;
        let test = test.args(["--", "--include-ignored"]);
        // These poison the variables the Docker provider must ignore: passed on to `docker`,
        // they would steer it to an engine that doesn't exist, or to TLS without certificates,
        // so the Docker tests fail unless the provider clears `docker`'s environment.
        let test = test
            .env("DOCKER_HOST", "unix:///nonexistent/pumpkin-poison.sock")
            .env("DOCKER_CONTEXT", "pumpkin-poison-no-such-context")
            .env("DOCKER_TLS_VERIFY", "1");
        test.env("PUMPKIN_SANDBOXD", &sandboxd).run()?;
    } else {
        test.run()?;
    }
    Ok(())
}

/// Builds the static `sandboxd` that every sandbox runs, and returns the path cargo reports
/// for it, so that the path is right wherever cargo's configuration puts the target directory.
fn sandboxd(sh: &Shell) -> Result<PathBuf> {
    let build = cmd!(
        sh,
        "cargo build --release --locked --package pumpkin-sandboxd --target {MUSL} --message-format json-render-diagnostics"
    );
    // One JSON message per line; diagnostics are rendered on standard error instead.
    for line in build.read()?.lines() {
        let message: serde_json::Value = serde_json::from_str(line)?;
        if message["reason"] == "compiler-artifact"
            && message["target"]["name"] == "sandboxd"
            && let Some(path) = message["executable"].as_str()
        {
            return Ok(path.into());
        }
    }
    Err("cargo reported no sandboxd executable: expected a compiler-artifact message for it".into())
}
